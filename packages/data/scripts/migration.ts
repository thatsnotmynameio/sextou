// Renders the migrations drizzle-kit generated into src/migration.gen.ts, so
// the server, its bundle and the tests import plain TypeScript instead of
// reading SQL files at runtime.
//
//   pnpm --filter @sextou/data migration --name <change>
//     generates a migration from src/schema.ts, then renders
//   pnpm --filter @sextou/data migration
//     renders only, after editing a generated migration.sql

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { readMigrationFolder } from '../src/migration-files.ts';

const root = join(import.meta.dirname, '..');
const output = join(root, 'src', 'migration.gen.ts');

const { values } = parseArgs({
  args: process.argv.slice(2),
  strict: true,
  options: { name: { type: 'string' } },
});

if (values.name !== undefined) {
  execFileSync('drizzle-kit', ['generate', '--name', values.name], {
    cwd: root,
    stdio: 'inherit',
  });
}

const migrations = readMigrationFolder(join(root, 'migration'));
writeFileSync(
  output,
  `// Generated by scripts/migration.ts from migration/*/migration.sql: do not
// edit. Run \`pnpm --filter @sextou/data migration\` to render it again.
import type { Migration } from './migration-files';

export const migrations: Migration[] = ${JSON.stringify(migrations)};
`,
);
execFileSync('oxfmt', [output], { stdio: 'inherit' });
